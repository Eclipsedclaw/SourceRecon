#!/usr/bin/env bash

set -euo pipefail

PROJECT_DIRECTORY="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_FILE="${PROJECT_DIRECTORY}/config/local.mk"
TEMPORARY_FILE="${OUTPUT_FILE}.tmp"
CXX_PATH="$(command -v "${CXX:-g++}" 2>/dev/null || true)"
PROJECT_CXX_STANDARD="${PROJECT_CXX_STANDARD:-c++20}"

fail()
{
    printf 'configure.sh: ERROR: %s\n' "$1" >&2
    exit 1
}

first_executable()
{
    local name="$1"
    local candidate=""

    for candidate in \
        "${CONDA_PREFIX:-}/bin/${name}" \
        "${HOME}/micromamba/envs/root-env/bin/${name}" \
        "${HOME}/miniconda3/envs/root-env/bin/${name}" \
        "${HOME}/.conda/envs/root-env/bin/${name}" \
        "$(command -v "${name}" 2>/dev/null || true)"
    do
        if [[ -x "${candidate}" ]]
        then
            printf '%s\n' "${candidate}"
            return 0
        fi
    done

    return 1
}

highest_geant4_config()
{
    local candidate=""
    local version=""

    {
        command -v geant4-config 2>/dev/null || true
        find /opt "${HOME}" /usr/local \
            -type f -path '*/bin/geant4-config' ! -path '*-build/*' \
            -perm -u+x -print 2>/dev/null || true
    } | awk '!seen[$0]++' | while IFS= read -r candidate
    do
        version="$("${candidate}" --version 2>/dev/null | head -n 1 || true)"

        if [[ -n "${version}" ]]
        then
            printf '%s\t%s\n' "${version}" "${candidate}"
        fi
    done | sort -V -k1,1 | tail -n 1 | cut -f 2-
}

[[ -n "${CXX_PATH}" ]] || fail "C++ compiler was not found."

if ! printf 'int main() { return 0; }\n' | \
    "${CXX_PATH}" "-std=${PROJECT_CXX_STANDARD}" -x c++ -fsyntax-only - \
    >/dev/null 2>&1
then
    fail "${CXX_PATH} does not support -std=${PROJECT_CXX_STANDARD}."
fi

ROOT_CONFIG_PATH="${ROOT_CONFIG:-$(first_executable root-config || true)}"
GEANT4_CONFIG_PATH="${GEANT4_CONFIG:-$(highest_geant4_config || true)}"
[[ -x "${ROOT_CONFIG_PATH}" ]] || fail "root-config was not found."
[[ -x "${GEANT4_CONFIG_PATH}" ]] || fail "geant4-config was not found."

ROOT_PREFIX="$(${ROOT_CONFIG_PATH} --prefix)"
ROOT_LIBRARY_DIRECTORY="$(${ROOT_CONFIG_PATH} --libdir)"
GEANT4_PREFIX="$(${GEANT4_CONFIG_PATH} --prefix)"
GEANT4_LIBRARY_DIRECTORY=""

for candidate in "${GEANT4_PREFIX}/lib" "${GEANT4_PREFIX}/lib64"
do
    if compgen -G "${candidate}/libG4*.so*" >/dev/null
    then
        GEANT4_LIBRARY_DIRECTORY="${candidate}"
        break
    fi
done

[[ -n "${GEANT4_LIBRARY_DIRECTORY}" ]] || \
    fail "Geant4 shared libraries were not found below ${GEANT4_PREFIX}."

JSON_HEADER=""

for candidate in \
    "${CONDA_PREFIX:-}/include/nlohmann/json.hpp" \
    "${ROOT_PREFIX}/include/nlohmann/json.hpp" \
    "${HOME}/micromamba/envs/root-env/include/nlohmann/json.hpp" \
    "${HOME}/miniconda3/envs/root-env/include/nlohmann/json.hpp" \
    "/usr/include/nlohmann/json.hpp" \
    "/usr/local/include/nlohmann/json.hpp"
do
    if [[ -f "${candidate}" ]]
    then
        JSON_HEADER="${candidate}"
        break
    fi
done

[[ -n "${JSON_HEADER}" ]] || fail "nlohmann/json.hpp was not found."
JSON_INCLUDE_DIRECTORY="${JSON_HEADER%/nlohmann/json.hpp}"

# 使用旧式 DT_RPATH，避免共享服务器里旧 Geant4 的 LD_LIBRARY_PATH
# 抢在本实验指定的 Geant4 11.2 之前被加载。
RPATH_FLAGS="-Wl,--disable-new-dtags -Wl,-rpath,${ROOT_LIBRARY_DIRECTORY}"
RPATH_FLAGS+=" -Wl,-rpath,${GEANT4_LIBRARY_DIRECTORY}"

{
    printf '# Generated by doppler_v7_experiment/configure.sh\n'
    printf 'DOPPLER_EXPERIMENT_CONFIGURED := 1\n'
    printf 'PROJECT_CXX_STANDARD := %s\n' "${PROJECT_CXX_STANDARD}"
    printf 'CXX := %s\n' "${CXX_PATH}"
    printf 'ROOT_CONFIG := %s\n' "${ROOT_CONFIG_PATH}"
    printf 'GEANT4_CONFIG := %s\n' "${GEANT4_CONFIG_PATH}"
    printf 'JSON_CFLAGS := -I%s\n' "${JSON_INCLUDE_DIRECTORY}"
    printf 'DOPPLER_RPATH_FLAGS := %s\n' "${RPATH_FLAGS}"
} > "${TEMPORARY_FILE}"

mv "${TEMPORARY_FILE}" "${OUTPUT_FILE}"

printf 'Configuration written to %s\n' "${OUTPUT_FILE}"
printf 'ROOT:    %s\n' "${ROOT_CONFIG_PATH}"
printf 'Geant4:  %s (%s)\n' \
    "${GEANT4_CONFIG_PATH}" \
    "$("${GEANT4_CONFIG_PATH}" --version | head -n 1)"
printf 'JSON:    %s\n' "${JSON_HEADER}"
printf 'Next: make all\n'
